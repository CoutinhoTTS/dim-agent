//! SessionStore's title metadata (S5b, design/appserver/session-title-metadata.md):
//! one title per Session with a revision, changed only by a revision-checked
//! `setTitle` and announced on the Session's broadcast channel after each
//! commit. The title never enters a Timeline.
use super::{SessionStore, SqliteStorage};
use dim_agent_capabilities::session_broadcast::{SessionNotice, notify};
use dim_agent_runtime::AgentError;
use rusqlite::{
    Connection, OptionalExtension, TransactionBehavior, params,
    types::{FromSql, FromSqlError, FromSqlResult, ToSql, ToSqlOutput, ValueRef},
};
use rutis::Ctx;
use rutis::host::CtxHost;
use rutis_bridge::session::{Error, HostDispatch, Reply, Value as RpcValue};
use serde::{Deserialize, Deserializer, Serialize, de::DeserializeOwned};
use serde_json::{Value, json};
use std::sync::{Arc, Mutex};
use tokio_util::task::TaskTracker;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TitleSource {
    /// Generated by SessionTitle.
    Auto,
    /// Set through `session.rename`.
    Manual,
}
impl ToSql for TitleSource {
    fn to_sql(&self) -> rusqlite::Result<ToSqlOutput<'_>> {
        Ok(match self {
            Self::Auto => "auto",
            Self::Manual => "manual",
        }
        .into())
    }
}
impl FromSql for TitleSource {
    fn column_result(value: ValueRef<'_>) -> FromSqlResult<Self> {
        match value.as_str()? {
            "auto" => Ok(Self::Auto),
            "manual" => Ok(Self::Manual),
            _ => Err(FromSqlError::InvalidType),
        }
    }
}

/// A Session's title. SessionStore stores the text as given; the title rules
/// belong to its writer, SessionTitle.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Title {
    pub text: String,
    pub source: TitleSource,
}

/// The `read` reply: the count of committed title writes (0 when never
/// written) and the current title.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SessionMetadata {
    pub revision: u64,
    pub title: Option<Title>,
}

/// The title fields of a v3 Session list entry, which are also the title
/// notice's `data`: a client copies a notice into its entry when
/// `titleRevision` is higher.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct TitleFields {
    pub title: Option<String>,
    pub title_source: Option<TitleSource>,
    pub title_revision: u64,
}
impl From<SessionMetadata> for TitleFields {
    fn from(metadata: SessionMetadata) -> Self {
        let (title, title_source) = match metadata.title {
            Some(Title { text, source }) => (Some(text), Some(source)),
            None => (None, None),
        };
        Self {
            title,
            title_source,
            title_revision: metadata.revision,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum MetadataError {
    /// `expectedRevision` is not the current revision.
    #[error("the title revision changed")]
    Conflict,
    /// The store holds no record of the Session.
    #[error("the Session is not stored")]
    NotFound,
    #[error("{0}")]
    Storage(String),
}
impl MetadataError {
    fn code(&self) -> &'static str {
        match self {
            Self::Conflict => "conflict",
            Self::NotFound => "not_found",
            Self::Storage(_) => "storage",
        }
    }
}
impl From<AgentError> for MetadataError {
    fn from(error: AgentError) -> Self {
        Self::Storage(error.to_string())
    }
}
impl From<rusqlite::Error> for MetadataError {
    fn from(error: rusqlite::Error) -> Self {
        Self::Storage(error.to_string())
    }
}

/// SessionStore's title writer. A `setTitle` is admitted when it is called
/// and runs as SessionStore's own task, which `close` waits for. One write
/// runs at a time, process-wide, and announces its commit before the next
/// starts, so the notices of a Session follow commit order.
#[derive(Clone)]
pub(super) struct Titles(Arc<TitleWriter>);
struct TitleWriter {
    db: Arc<SqliteStorage>,
    /// SessionStore's context, which announces commits.
    ctx: Ctx,
    /// Orders each admission against `close`.
    admission: Mutex<()>,
    /// The admitted writes; closed once SessionStore is closing.
    writes: TaskTracker,
    /// Held by the write in progress: one runs at a time.
    turn: tokio::sync::Mutex<()>,
}
impl Titles {
    pub(super) fn new(db: Arc<SqliteStorage>, ctx: Ctx) -> Self {
        Self(Arc::new(TitleWriter {
            db,
            ctx,
            admission: Mutex::new(()),
            writes: TaskTracker::new(),
            turn: tokio::sync::Mutex::new(()),
        }))
    }
    /// Stops admitting writes, then waits until every admitted write, the
    /// one in progress and those waiting for their turn, has committed and
    /// announced or failed.
    pub(super) async fn close(&self) {
        {
            let _admission = self.0.admission.lock().unwrap();
            self.0.writes.close();
        }
        self.0.writes.wait().await;
    }
}
impl TitleWriter {
    async fn settle(
        self: Arc<Self>,
        session_id: String,
        expected_revision: u64,
        title: Option<Title>,
    ) -> Result<u64, MetadataError> {
        let _turn = self.turn.lock().await;
        #[cfg(feature = "testing")]
        testing::pause(&session_id).await;
        let (id, written) = (session_id.clone(), title.clone());
        let revision = self
            .db
            .run(move |connection| Ok(write(connection, &id, expected_revision, written.as_ref())))
            .await??;
        let data = TitleFields::from(SessionMetadata { revision, title });
        notify(
            &self.ctx,
            &session_id,
            SessionNotice {
                source: "SessionStore".into(),
                kind: "title".into(),
                data: serde_json::to_value(data).expect("title fields are JSON"),
            },
        );
        Ok(revision)
    }
}

impl SessionStore {
    /// The Session's title and revision. Never loads the Session.
    pub async fn metadata(&self, session_id: &str) -> Result<SessionMetadata, MetadataError> {
        let id = session_id.to_owned();
        self.titles
            .0
            .db
            .run_read(move |connection| Ok(read(connection, &id)))
            .await?
    }
    /// Commits `title` as revision `expected_revision + 1` and announces it.
    /// The call is the handover: unless SessionStore is closing, it admits
    /// the write and starts it as SessionStore's own task before returning.
    /// The returned future only awaits that task, and dropping it detaches
    /// the reply, never the write.
    pub fn set_title(
        &self,
        session_id: &str,
        expected_revision: u64,
        title: Option<Title>,
    ) -> impl Future<Output = Result<u64, MetadataError>> + Send + 'static {
        let titles = &self.titles.0;
        let admitted = {
            let _admission = titles.admission.lock().unwrap();
            if titles.writes.is_closed() {
                Err(MetadataError::Storage("SessionStore is closing".into()))
            } else {
                let write = titles
                    .clone()
                    .settle(session_id.to_owned(), expected_revision, title);
                Ok(titles.writes.spawn_on(write, titles.ctx.handle()))
            }
        };
        async move {
            admitted?
                .await
                .map_err(|error| MetadataError::Storage(error.to_string()))?
        }
    }
}

/// Decodes `revision, title, title_source` from column `first` on: a
/// `session_metadata` row left-joined to its Session, all NULL without one.
pub(super) fn decode(row: &rusqlite::Row<'_>, first: usize) -> rusqlite::Result<SessionMetadata> {
    let revision = row
        .get::<_, Option<i64>>(first)?
        .map(|revision| {
            u64::try_from(revision)
                .map_err(|_| rusqlite::Error::IntegralValueOutOfRange(first, revision))
        })
        .transpose()?;
    let text: Option<String> = row.get(first + 1)?;
    let source: Option<TitleSource> = row.get(first + 2)?;
    Ok(SessionMetadata {
        revision: revision.unwrap_or(0),
        title: text
            .zip(source)
            .map(|(text, source)| Title { text, source }),
    })
}
fn read(connection: &Connection, session_id: &str) -> Result<SessionMetadata, MetadataError> {
    connection
        .query_row(
            "SELECT m.revision, m.title, m.title_source FROM agent_sessions s \
             LEFT JOIN session_metadata m ON m.session_id = s.session_id WHERE s.session_id = ?1",
            [session_id],
            |row| decode(row, 0),
        )
        .optional()?
        .ok_or(MetadataError::NotFound)
}
fn write(
    connection: &mut Connection,
    session_id: &str,
    expected_revision: u64,
    title: Option<&Title>,
) -> Result<u64, MetadataError> {
    let tx = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
    if read(&tx, session_id)?.revision != expected_revision {
        return Err(MetadataError::Conflict);
    }
    let revision = expected_revision + 1;
    tx.execute(
        "INSERT INTO session_metadata (session_id, revision, title, title_source) VALUES (?1, ?2, ?3, ?4) \
         ON CONFLICT (session_id) DO UPDATE SET revision = excluded.revision, title = excluded.title, \
         title_source = excluded.title_source",
        params![
            session_id,
            i64::try_from(revision).map_err(|error| MetadataError::Storage(error.to_string()))?,
            title.map(|title| &title.text),
            title.map(|title| title.source),
        ],
    )?;
    tx.commit()?;
    Ok(revision)
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct ReadRequest {
    session_id: String,
}
#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct SetTitleRequest {
    session_id: String,
    expected_revision: u64,
    /// Required: `null` clears, and an omitted title is refused rather than
    /// read as a clear.
    #[serde(deserialize_with = "present")]
    title: Option<Title>,
}
fn present<'de, D: Deserializer<'de>>(value: D) -> Result<Option<Title>, D::Error> {
    Option::deserialize(value)
}
/// One request object; anything else is the caller's programming error.
fn request<T: DeserializeOwned>(args: RpcValue) -> Result<T, Error> {
    let invalid = |detail: String| {
        Error::Value(format!(
            "expected one sessionMetadata request object: {detail}"
        ))
    };
    let Value::Array(args) = args.json()? else {
        return Err(invalid("not an argument list".into()));
    };
    let [request] = <[Value; 1]>::try_from(args)
        .map_err(|args| invalid(format!("{} arguments", args.len())))?;
    serde_json::from_value(request).map_err(|error| invalid(error.to_string()))
}
/// `{ok: true, value}` or `{ok: false, error: {code, message}}`, as `settings`.
fn envelope(result: Result<impl Serialize, MetadataError>) -> RpcValue {
    match result {
        Ok(value) => json!({"ok": true, "value": value}),
        Err(error) => {
            json!({"ok": false, "error": {"code": error.code(), "message": error.to_string()}})
        }
    }
    .into()
}

/// `sessionMetadata` by name for every language (S5b §4.1). It carries no
/// caller identity; SessionTitle is the title's one writer by design.
pub(super) struct Dispatch(pub(super) Arc<SessionStore>);
impl HostDispatch for Dispatch {
    fn methods(&self) -> Option<Value> {
        Some(json!({"read": "async", "setTitle": "async"}))
    }
    fn invoke(&self, method: &str, args: RpcValue) -> Reply {
        match method {
            "read" => {
                let ReadRequest { session_id } = request(args)?;
                let store = self.0.clone();
                Ok(RpcValue::future(async move {
                    Ok(envelope(store.metadata(&session_id).await))
                }))
            }
            "setTitle" => {
                let SetTitleRequest {
                    session_id,
                    expected_revision,
                    title,
                } = request(args)?;
                let reply = self.0.set_title(&session_id, expected_revision, title);
                Ok(RpcValue::future(async move {
                    Ok(envelope(
                        reply.await.map(|revision| json!({"revision": revision})),
                    ))
                }))
            }
            _ => Err(Error::Value(format!(
                "unknown sessionMetadata method {method}"
            ))),
        }
    }
}

/// Holds a title write for race flow tests. Feature `testing` only;
/// production builds have no hook.
#[cfg(feature = "testing")]
pub mod testing {
    use std::sync::Mutex;
    use tokio::sync::oneshot;

    type Hold = (String, oneshot::Sender<()>, oneshot::Receiver<()>);
    static HOLDS: Mutex<Vec<Hold>> = Mutex::new(Vec::new());

    /// Holds the next admitted `setTitle` of a Session in its turn, before
    /// its transaction, until this is dropped.
    pub struct HeldWrite {
        arrived: oneshot::Receiver<()>,
        _release: oneshot::Sender<()>,
    }
    impl HeldWrite {
        /// Resolves once the held write has arrived.
        pub async fn arrived(&mut self) {
            let _ = (&mut self.arrived).await;
        }
    }

    pub fn hold_title_write(session_id: &str) -> HeldWrite {
        let (arrive, arrived) = oneshot::channel();
        let (release, released) = oneshot::channel();
        HOLDS
            .lock()
            .unwrap()
            .push((session_id.to_owned(), arrive, released));
        HeldWrite {
            arrived,
            _release: release,
        }
    }

    pub(super) async fn pause(session_id: &str) {
        let hold = {
            let mut holds = HOLDS.lock().unwrap();
            let index = holds.iter().position(|(held, ..)| held == session_id);
            index.map(|index| holds.swap_remove(index))
        };
        if let Some((_, arrive, released)) = hold {
            let _ = arrive.send(());
            let _ = released.await;
        }
    }
}
